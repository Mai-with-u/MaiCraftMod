package org.maiwithu.maicraft.behavior.inventory;

/**
 * 物品价值分级：腾地方时把物品从贵到贱排，越靠前越不能动。
 *
 * <p>腾背包只做可逆的搬动（合并、存网络、塞随身背包、存进容器），不动的东西从垃圾级开始存：
 * 垃圾 → 顺手捡的零碎 → 建材 → 食物；"有用的"及以上不自动挪。分级的用处是排存放顺序
 * 和腾不出时给调用方列可丢的候选，丢不丢由调用方拿主意，Mod 不再替人扔东西。
 */
enum Worth {
    /** 要留的东西：预留的、这个任务正要用的，动都不动。 */
    KEPT,
    /** 工具、武器、护甲：干活和保命靠它。 */
    GEAR,
    /** 稀有贵重：带附魔、标了稀有度，丢了很难补回来。 */
    PRECIOUS,
    /** 有用的：做出来的零件、锭、机器方块，说不准哪天要用的材料。 */
    USEFUL,
    /** 能吃的：饿了要靠它。 */
    FOOD,
    /** 整块建材：能搭能垫，也最容易再弄到。 */
    BUILDING_MATERIAL,
    /** 顺手捡的零碎：树苗、蘑菇、花、种子、生肉、蜘蛛眼、骨头这类意料之外又没什么用的战利品。 */
    INCIDENTAL,
    /** 垃圾：堆多了一文不值的方块和腐肉。 */
    JUNK;
}
