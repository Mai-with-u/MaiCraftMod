package org.maiwithu.maicraft.behavior.survival.beds;

/**
 * 一张候选床被排除时的原因，能进找床失败话术按原因计数的那几种。
 *
 * <p>有些拒绝发生在点床那一刻（怪是走近后才到的、占用是躺下那一刻才被原版判的），
 * 有些发生在走近途中（床没了、被挡住走不到跟前）。把原因跟着床一起记进排除名单，
 * 找床失败的话术才分得清"床边有怪几张、被占用几张、哪张已经不在了"，
 * 不至于统统算成"试过睡不上"。
 */
public enum BedRefusal {
    /** 躺下时被原版以"这张床已被占用"拒绝。 */
    OCCUPIED,
    /** 躺下时被原版以"周围有怪物在游荡"拒绝。 */
    MONSTERS_NEARBY,
    /** 床太远或被挡住（点床被原版这样拒、换过站位还是不行），或去床边的路走不通：这张床点不上。 */
    BLOCKED,
    /** 走到床边发现床已经不在了（途中被拆）：这条是游戏事实，这张床不再试。 */
    GONE,
}
