package org.maiwithu.maicraft.kernel.interrupt;

/**
 * 任务特征接口：压在主任务身上的临时任务此刻占着身体在等一个时间条件（正睡着等天亮这类），
 * 由它声明，控制循环据此在 LLM 换活、取消旧目标时叫它起身让出身体。
 *
 * <p>睡着等天亮的时间条件在时间冻结的世界里永远等不到，而身体的动作又被 "正在干活" 挡住，
 * 调用方的每一条新指令都只能在后面排队、再被更新的提交顶掉——起身是几刻的游戏结算，
 * 让位不与新指令冲突。任务被叫起后会尽快以没做完收场，它的生存需求照"没做成"先缓一阵，
 * 新的主任务才有空当动起来。
 */
public interface WakesForNewOrders {

    /**
     * 被新指令叫起。此刻确实占着身体在等的任务记下这件事并开始起身，返回真；
     * 不在此刻占着身体的任务什么都不做，返回假。
     */
    boolean wakeForNewOrders();
}
